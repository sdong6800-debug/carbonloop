'use strict';
const assert=require('node:assert/strict'),{chromium}=require('playwright');
const testUrl=process.env.CARBONLOOP_TEST_URL||'http://127.0.0.1:8513/demo.html';
(async()=>{
 const latest=await fetch('http://127.0.0.1:8515/rhino-intake/latest').then(response=>response.json());
 assert.equal(latest.available,true);
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  await page.route('http://127.0.0.1:8515/rhino-intake/latest',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(latest)}));
  await page.goto(testUrl);
  await page.waitForFunction(()=>document.querySelector('.entry-badge')?.textContent.includes('Rhino 已连接'));
  await page.waitForFunction(()=>!document.querySelector('#entryRead')?.disabled);
  const connected=(await page.locator('.page-heading .status').innerText()).trim();
  await page.click('#entryRead');
  const button=(await page.textContent('#entryConfirmGroup')).trim();
  const recognition=(await page.textContent('#entryRecognition')).trim();
  const similarCount=(await page.textContent('#entrySimilarCount')).trim();
  const groupButton=(await page.textContent('#entryConfirmOne')).trim();
  const detailAllButton=(await page.textContent('#entryConfirmAllDetail')).trim();
  const match=button.match(/^一键确认全部已识别构件（(\d+)）$/);
  assert.ok(match&&Number(match[1])>1,'real Rhino review must default to all recognized objects, not one material group');
  assert.match(recognition,/构件：楼地面饰面/);
  assert.match(recognition,/材料：抛光天然石材/);
  assert.equal(similarCount,'');
  assert.equal(groupButton,'仅确认当前构件');
  assert.equal(detailAllButton,button.replace(/^一键/,''));
  await page.screenshot({path:'.test-exports/current-rhino-review.png',fullPage:false});
  await page.click('#entryConfirmGroup');
  await page.check('#entryPartial');
  await page.click('#entryContinue');
  await page.waitForFunction(()=>document.querySelector('#reportStages')?.textContent.trim().length>0);
  const stage=(await page.locator('#reportStages').textContent()).replace(/\s+/g,' ');
  const coverage=(await page.textContent('#reportCoverageTitle')).trim();
  assert.match(coverage,/当前仅覆盖 \d+ \/ \d+ 个构件/);
  await page.screenshot({path:'.test-exports/current-rhino-fixed.png',fullPage:true});
  await page.click('.component-disclosure>summary');
  const stoneRow=page.locator('#reportComponents tr').filter({hasText:'抛光天然石材'}).first();
  assert.match((await stoneRow.textContent()).replace(/\s+/g,' '),/m² · 15 mm (?:参考|候选厚度)/);
  assert.notEqual((await page.textContent('#total')).trim(),'242.4');
  await page.click('#reportExplore');await page.click('#solutionFind');await page.waitForFunction(()=>!document.getElementById('solutionFind').disabled);
  const solutionCount=await page.locator('.solution-card').count(),solutionTitles=await page.locator('.solution-card h3').allTextContents();assert(solutionCount>0);assert(solutionTitles.some(title=>title.includes('抛光天然石材')&&title.includes('实木')));
  console.log(JSON.stringify({connected,recognition,button,detailAllButton,groupButton,coverage,total:(await page.textContent('#total')).trim(),stage,solutionCount,solutionTitles},null,2));
  console.log('PASS current Rhino intake defaults to all recognized objects, labels ext.Finish as floor finish, uses the 15 mm area basis, and generates bounded material research candidates.');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
