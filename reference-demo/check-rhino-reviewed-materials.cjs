'use strict';
const assert=require('node:assert/strict');
const M=require('./material-intake.js'),R=require('./rhino-contract.js'),C=require('./model-core.js');
const reviewed=(name,category)=>({name,originalName:name,productType:category,review:{confirmed:true,version:'rhino-review-1'},inference:{source:'rhino-user-confirmed',basis:'Rhino 用户确认'}});
assert.equal(M.match(reviewed('timbre','timber-solid')).material,'timber-solid');
assert.equal(M.match(reviewed('wood effect tile','finish')).material,'finish');
assert.equal(M.match(reviewed('glass','unknown')).material,'unknown');
assert.equal(M.match({...reviewed('glass','timber-solid'),review:{confirmed:false}}).material,'unknown');
assert.equal(M.match(reviewed('custom product','invented')).material,'unknown');
assert.equal(M.match({name:'wood effect tile'}).material,'unknown');
assert.equal(M.match({name:'wood'}).material,'timber-solid');
const payload={schemaVersion:R.VERSION,source:{host:'Rhino',documentId:'review-test',unitSystem:'Meters'},selection:{mode:'selection'},objects:[{id:'a',name:'floor slab',typeHint:'slab',typeInference:{source:'CarbonLoop.Type',basis:'Rhino 确认'},floor:'1F',layer:'floor::ext.Finish',geometry:{origin:[0,0,0],dimensions:[6,4,.2]},material:reviewed('timbre','timber-solid'),quantity:{kind:'net-volume',value:4.8},quantityRequired:true}]};
const normalized=R.normalize(payload);assert.ok(normalized.valid);
assert.equal(normalized.objects[0].type,'slab','网页 Finish guard 不覆盖 Rhino 显式确认');
const row={...normalized.objects[0],...M.match(normalized.objects[0].materialRecord)};
assert.equal(row.classificationSource,'rhino_user_confirmed');
assert.equal(row.materialRecord.originalName,'timbre');
assert.ok(!C.element(row).error,'用户确认的材料和净体积可以进入计算');
assert.equal(C.element(row).volume,4.8);
console.log('PASS reviewed mapping, explicit unknown, stale/invalid rejection, original provenance, Rhino contract and calculable quantity');
